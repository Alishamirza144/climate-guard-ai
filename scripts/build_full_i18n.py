def generate_locale_for(lang_code: str) -> dict:
    if lang_code in LANG_TRANSLATIONS:
        return LANG_TRANSLATIONS[lang_code]
    
    # Base fallback is Hindi for Devanagari languages, Urdu for Perso-Arabic, Bengali for Eastern, English otherwise
    if lang_code in ("ks", "sd"):
        base = json.loads(json.dumps(LANG_TRANSLATIONS["ur"]))
    elif lang_code in ("ne", "kok", "mai", "doi", "brx", "sa"):
        base = json.loads(json.dumps(LANG_TRANSLATIONS["hi"]))
    elif lang_code in ("sat", "mni"):
        base = json.loads(json.dumps(LANG_TRANSLATIONS["bn"]))
    else:
        base = json.loads(json.dumps(EN))
        
    # Apply specialized regional titles if present
    if lang_code in SPECIAL_TITLES:
        spec = SPECIAL_TITLES[lang_code]
        if "title" in spec: base["app"]["title"] = spec["title"]
        if "subtitle" in spec: base["app"]["subtitle"] = spec["subtitle"]
        if "nationalIntelligence" in spec: base["app"]["nationalIntelligence"] = spec["nationalIntelligence"]
        if "language" in spec: base["app"]["language"] = spec["language"]
        if "selectLanguage" in spec: base["app"]["selectLanguage"] = spec["selectLanguage"]
        if "searchLanguage" in spec: base["app"]["searchLanguage"] = spec["searchLanguage"]
        if "dashboard" in spec: base["nav"]["dashboard"] = spec["dashboard"]
        if "commandHub" in spec: base["dashboard"]["commandHub"] = spec["commandHub"]
        if "floodRisk" in spec: base["dashboard"]["floodRisk"] = spec["floodRisk"]
        if "heatRisk" in spec: base["dashboard"]["heatRisk"] = spec["heatRisk"]
        if "wildfireRisk" in spec: base["dashboard"]["wildfireRisk"] = spec["wildfireRisk"]
        if "cropRisk" in spec: base["dashboard"]["cropRisk"] = spec["cropRisk"]
        if "drainageRisk" in spec: base["dashboard"]["drainageRisk"] = spec["drainageRisk"]
        if "insufficient" in spec: base["risk"]["insufficient"] = spec["insufficient"]
        if "safeConditions" in spec: base["alerts"]["safeConditions"] = spec["safeConditions"]
        if "selectCity" in spec: base["city"]["selectCity"] = spec["selectCity"]
        
    return base

