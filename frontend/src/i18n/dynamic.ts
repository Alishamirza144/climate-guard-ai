import { TFunction } from 'i18next'

// Weather condition mappings
const WEATHER_KEY_MAP: Record<string, string> = {
  'clear sky': 'weather.clearSky',
  'mainly clear': 'weather.mainlyClear',
  'partly cloudy': 'weather.partlyCloudy',
  'overcast': 'weather.overcast',
  'fog': 'weather.fog',
  'drizzle': 'weather.drizzle',
  'rain': 'weather.rain',
  'heavy rain': 'weather.heavyRain',
  'thunderstorm': 'weather.thunderstorm',
}

/**
 * Translates dynamic weather condition descriptions (e.g. "Mainly clear", "Partly Cloudy").
 */
export function translateWeatherCondition(condition: string | undefined | null, t: TFunction): string {
  if (!condition) return t('weather.partlyCloudy', 'Partly cloudy')
  const clean = condition.trim().toLowerCase()

  const directKey = WEATHER_KEY_MAP[clean]
  if (directKey) {
    return t(directKey, condition)
  }

  if (clean.includes('mainly clear')) return t('weather.mainlyClear', condition)
  if (clean.includes('clear')) return t('weather.clearSky', condition)
  if (clean.includes('partly')) return t('weather.partlyCloudy', condition)
  if (clean.includes('overcast')) return t('weather.overcast', condition)
  if (clean.includes('heavy rain')) return t('weather.heavyRain', condition)
  if (clean.includes('thunder')) return t('weather.thunderstorm', condition)
  if (clean.includes('rain')) return t('weather.rain', condition)
  if (clean.includes('fog')) return t('weather.fog', condition)
  if (clean.includes('drizzle')) return t('weather.drizzle', condition)

  return condition
}

/**
 * Translates dynamic alert titles (e.g. "✅ NO ACTIVE FLOOD THREAT – MUMBAI REGION").
 */
export function translateAlertTitle(title: string | undefined | null, t: TFunction): string {
  if (!title) return ''
  const trimmed = title.trim()

  // Match "NO ACTIVE FLOOD THREAT – {CITY} REGION"
  const matchNoThreat = trimmed.match(/(?:✅\s*)?NO ACTIVE FLOOD THREAT\s*[-–—]\s*(.+?)(?:\s+REGION)?$/i)
  if (matchNoThreat) {
    const city = matchNoThreat[1].trim()
    return t('dynamicAlerts.noFloodThreatTitle', {
      city,
      defaultValue: `✅ ${t('alerts.noActiveAlerts', 'No Active Flood Threat')} – ${city}`,
    })
  }

  // Match "INSUFFICIENT DATA – {CITY} REGION"
  const matchInsufficient = trimmed.match(/(?:ℹ️\s*)?INSUFFICIENT (?:TELEMETRY )?DATA\s*[-–—]\s*(.+?)(?:\s+REGION)?$/i)
  if (matchInsufficient) {
    const city = matchInsufficient[1].trim()
    return t('dynamicAlerts.insufficientDataTitle', {
      city,
      defaultValue: `ℹ️ ${t('risk.insufficient', 'Insufficient Data')} – ${city}`,
    })
  }

  // Match "FLOOD WARNING – {CITY} REGION"
  const matchWarning = trimmed.match(/(?:⚠️\s*)?FLOOD WARNING\s*[-–—]\s*(.+?)(?:\s+REGION)?$/i)
  if (matchWarning) {
    const city = matchWarning[1].trim()
    return t('dynamicAlerts.floodWarningTitle', {
      city,
      defaultValue: `⚠️ ${t('risk.warning', 'Flood Warning')} – ${city}`,
    })
  }

  // Match "FLOOD WATCH – {CITY} REGION"
  const matchWatch = trimmed.match(/(?:⚠️\s*)?FLOOD WATCH\s*[-–—]\s*(.+?)(?:\s+REGION)?$/i)
  if (matchWatch) {
    const city = matchWatch[1].trim()
    return t('dynamicAlerts.floodWatchTitle', {
      city,
      defaultValue: `⚠️ ${t('risk.watch', 'Flood Watch')} – ${city}`,
    })
  }

  // Match "FLOOD CRITICAL – {CITY} REGION"
  const matchCritical = trimmed.match(/(?:🚨\s*)?FLOOD CRITICAL\s*[-–—]\s*(.+?)(?:\s+REGION)?$/i)
  if (matchCritical) {
    const city = matchCritical[1].trim()
    return t('dynamicAlerts.floodCriticalTitle', {
      city,
      defaultValue: `🚨 ${t('risk.critical', 'Flood Critical')} – ${city}`,
    })
  }

  return title
}

/**
 * Translates dynamic causal reason messages generated by backend engines.
 */
export function translateAlertReason(
  reason: string | undefined | null,
  t: TFunction,
  city?: string,
  state?: string,
): string {
  if (!reason) return ''
  const trimmed = reason.trim()

  if (trimmed.includes('No significant rainfall recorded in') || trimmed.includes('remain within nominal limits')) {
    const c = city || 'Region'
    const s = state || 'India'
    return t('dynamicAlerts.noRainReason', { city: c, state: s, defaultValue: reason })
  }

  if (trimmed.includes('is currently synchronizing') || trimmed.includes('marked insufficient')) {
    const c = city || 'Catchment'
    return t('dynamicAlerts.syncReason', { city: c, defaultValue: reason })
  }

  if (trimmed.includes('Elevated hydrometeorological risk signals detected')) {
    const c = city || 'Catchment'
    return t('dynamicAlerts.elevatedSignalsReason', { city: c, defaultValue: reason })
  }

  return reason
}

/**
 * Translates recommended action protocols from backend early warning models.
 */
export function translateRecommendedAction(
  action: string | undefined | null,
  t: TFunction,
  city?: string,
): string {
  if (!action) return ''
  const trimmed = action.trim()

  if (trimmed.includes('Routine civic monitoring') || trimmed.includes('Municipal advisories')) {
    const c = city || 'Municipal'
    return t('dynamicAlerts.routineMonitoringAction', { city: c, defaultValue: action })
  }

  if (trimmed.includes('Awaiting updated sensor telemetry') || trimmed.includes('district administration bulletins')) {
    return t('dynamicAlerts.awaitingTelemetryAction', { defaultValue: action })
  }

  return action
}

/**
 * Translates latency statuses into user's language.
 */
export function translateLatencyStatus(status: string, t: TFunction): string {
  if (status === 'green') return t('latency.normal', 'Normal Latency')
  if (status === 'amber') return t('latency.delay', 'Propagation Delay')
  return t('latency.lag', 'Network Lag / Fault')
}
