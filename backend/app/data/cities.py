def find_nearest_city(lat: float, lon: float) -> dict[str, Any]:
    """Find the closest supported Indian city by Euclidean distance."""
    best = INDIA_CITIES[0]
    min_dist = float("inf")
    for city in INDIA_CITIES:
        dist = (city["lat"] - lat) ** 2 + (city["lon"] - lon) ** 2
        if dist < min_dist:
            min_dist = dist
            best = city
    return best


